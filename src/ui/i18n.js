const STRINGS = { en: EN, de: DE, es: ES, fr: FR };

export const LANGUAGES = [
  ["en", "English"],
  ["de", "Deutsch"],
  ["es", "Español"],
  ["fr", "Français"],
];

let lang = "en";

// "auto" follows the language Figma's window reports.
export function setLanguage(choice) {
  const detected = (navigator.language || "en").slice(0, 2).toLowerCase();
  lang = STRINGS[choice] ? choice : STRINGS[detected] ? detected : "en";
  document.documentElement.lang = lang;
}

export function has(key) {
  return key in EN;
}

export function num(value, digits = 2, grouping = true) {
  return new Intl.NumberFormat(lang, { maximumFractionDigits: digits, useGrouping: grouping }).format(value);
}

// "left, top and right" in the current language.
export function list(items) {
  return new Intl.ListFormat(lang, { style: "long", type: "conjunction" }).format(items);
}

export function t(key, vars) {
  let text = key in STRINGS[lang] ? STRINGS[lang][key] : EN[key];
  if (text === undefined) return key;
  const values = vars || {};
  if (typeof text === "object") text = text[new Intl.PluralRules(lang).select(values.n)] || text.other;
  const filled = text.replace(/\{(\w+)\}/g, (_, name) => (values[name] === undefined ? "" : typeof values[name] === "number" ? num(values[name]) : values[name]));

  // A number never wraps away from its unit.
  return filled.replace(/(\d) (?=(mm|in|pt|ppi|KB|MB|Mo|%)(\W|$))/g, "$1\u00a0");
}
